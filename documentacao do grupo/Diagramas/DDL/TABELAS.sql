CREATE TABLE DIM_QT_CHUVA (
  ANO INT,
  DIA INT,
  HORA INT,
  PRECIPITACAO_TOTAL_HORA FLOAT,
  UMIDADE_RELATIVA_AR FLOAT,

  PRIMARY KEY CLUSTERED (HORA, DIA, ANO)
)
GO

CREATE TABLE FATO_VOTOS (
    ANO_ELEICAO INT,
    NR_TURNO INT,
    CD_MUNICIPIO INT,
    NM_MUNICIPIO VARCHAR(255),
    NR_ZONA INT,
    NR_SECAO INT,
    QT_APTOS INT,
    QT_COMPARECIMENTO INT,
    QT_ABSTENCOES INT,
    QT_VOTOS_NOMINAIS INT,
    QT_VOTOS_BRANCOS INT,
    QT_VOTOS_NULOS INT,
    QT_VOTOS_LEGENDA INT,
    QT_VOTOS_ANULADOS_APU_SEP INT,
    NR_LOCAL_VOTACAO INT,
    NM_LOCAL_VOTACAO VARCHAR(255)
    PRIMARY KEY (NR_SECAO, NR_ZONA, CD_MUNICIPIO, NR_TURNO, NR_LOCAL_VOTACAO, ANO_ELEICAO)
);

