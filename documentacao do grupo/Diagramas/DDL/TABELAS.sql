GO

ALTER TABLE DIM_LOCALVOTACAO ADD FOREIGN KEY (NM_MUNICIPIO) REFERENCES DIM_MUNICIPIOS (NM_MUNICIPIO);
GO

ALTER TABLE DIM_IDHM_PROXY ADD FOREIGN KEY (NM_MUNICIPIO) REFERENCES DIM_MUNICIPIOS (NM_MUNICIPIO);
GO

ALTER TABLE DIM_IDHM_PROXY ADD FOREIGN KEY (ANO) REFERENCES DIM_ANO (ANO);
GO

ALTER TABLE DIM_QTDE_CHUVA ADD FOREIGN KEY (ANO, DIA) REFERENCES DIM_DIA (ANO, DIA);
