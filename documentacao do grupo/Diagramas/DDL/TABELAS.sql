CREATE TABLE DIM_MUNICIPIOS (
    CD_MUNICIPIO INT PRIMARY KEY NOT NULL,
    NM_MUNICIPIO VARCHAR(255)
);
GO

CREATE TABLE DIM_CANDIDATOS (
    SQ_CANDIDATOS BIGINT NOT NULL,
    NM_CANDIDATO NVARCHAR(255),
    NR_PARTIDO INT,
    NM_PARTIDO NVARCHAR(255),
    NR_TURNO INT NOT NULL,
    ANO INT NOT NULL,
    CONSTRAINT PK_DIM_CANDIDATOS PRIMARY KEY (SQ_CANDIDATOS, NR_TURNO)
);
GO

CREATE TABLE DIM_LOCALVOTACAO (
    CD_MUNICIPIO INT NOT NULL,
    NM_MUNICIPIO VARCHAR(255) NOT NULL,
    NR_ZONA INT NOT NULL,
    NR_SECAO INT NOT NULL,
    DS_TIPO_SECAO_AGREGADA VARCHAR(50),
    NR_SECAO_PRINCIPAL INT,
    NR_LOCAL_VOTACAO INT,
    NM_LOCAL_VOTACAO VARCHAR(150),
    DS_ENDERECO VARCHAR(255),
    NM_BAIRRO VARCHAR(100),
    NR_CEP CHAR(8),
    NR_LOCAL_VOTACAO_ORIGINAL INT,
    NM_LOCAL_VOTACAO_ORIGINAL VARCHAR(150),
    DS_ENDERECO_LOCVT_ORIGINAL VARCHAR(255),
    AA_ELEICAO VARCHAR(4)
    PRIMARY KEY (CD_MUNICIPIO, NM_MUNICIPIO, NR_ZONA, NR_SECAO, NR_SECAO_PRINCIPAL, NR_LOCAL_VOTACAO, DS_ENDERECO, NM_BAIRRO, NR_CEP, NR_LOCAL_VOTACAO_ORIGINAL, DS_ENDERECO_LOCVT_ORIGINAL, AA_ELEICAO)
);
GO

CREATE TABLE DIM_POSICAOGEOGRAFICA (
    ID_POSICAOGEOGRAFICA BIGINT IDENTITY(1,1) PRIMARY KEY,
    AA_ELEICAO INT,
    DS_ENDERECO_LOCVT_ORIGINAL NVARCHAR(255),
    NR_LATITUDE FLOAT,
    NR_LONGITUDE FLOAT,
    CD_MUNICIPIO INT
);
GO


CREATE TABLE DIM_IDHM_PROXY (
    NM_MUNICIPIO VARCHAR(255) NOT NULL,
    ANO INT NOT NULL,
    IDEB_AI DECIMAL(3, 1),
    IDEB_AF DECIMAL(3, 1),
    IDEB_EM DECIMAL(3, 1),
    PIB_PER_CAPITA DECIMAL(15, 2),
    COBERTURA_AGUA DECIMAL(5, 2),
    
    PRIMARY KEY CLUSTERED (NM_MUNICIPIO, ANO)
);
GO

CREATE TABLE DIM_PARTIDOS (
    ANO INT NOT NULL,
    SIGLA VARCHAR(20) NOT NULL,
    NOME VARCHAR(100) NOT NULL,
    POSICIONAMENTO VARCHAR(8) NOT NULL,
    CONSTRAINT PK_DIM_PARTIDOS PRIMARY KEY (ANO, SIGLA)
);
GO

