CREATE TABLE DIM_CANDIDATOS (
    SQ_CANDIDATOS INT PRIMARY KEY,
    NM_CANDIDATO NVARCHAR(255),
    NR_PARTIDO INT,
    NM_PARTIDO NVARCHAR(255),
    NR_TURNO INT,
    ANO INT NOT NULL
);
GO

CREATE TABLE DIM_MUNICIPIOS (
    NM_MUNICIPIO VARCHAR(150) PRIMARY KEY NOT NULL
);
GO


CREATE TABLE DIM_LOCALVOTACAO (
    CD_MUNICIPIO INT NOT NULL,
    NM_MUNICIPIO VARCHAR(150) NOT NULL,
    NR_ZONA INT NOT NULL,
    NR_SECAO INT NOT NULL PRIMARY KEY,
    DS_TIPO_SECAO_AGREGADA VARCHAR(50),
    NR_SECAO_PRINCIPAL INT,
    NR_LOCAL_VOTACAO INT,
    NM_LOCAL_VOTACAO VARCHAR(150),
    DS_ENDERECO VARCHAR(255),
    NM_BAIRRO VARCHAR(100),
    NR_CEP CHAR(8),
    NR_LOCAL_VOTACAO_ORIGINAL INT,
    NM_LOCAL_VOTACAO_ORIGINAL VARCHAR(150),
    DS_ENDERECO_LOCVT_ORIGINAL NVARCHAR(255)
);
GO

CREATE TABLE DIM_POSICAOGEOGRAFICA (
    DS_ENDERECO_LOCVT_ORIGINAL NVARCHAR(255) PRIMARY KEY,
    NR_LATITUDE FLOAT,
    NR_LONGITUDE FLOAT
);
GO

CREATE TABLE DIM_IDHM_PROXY (
    NM_MUNICIPIO VARCHAR(150) NOT NULL,
    ANO INT NOT NULL,
    IDEB_AI DECIMAL(3, 1),
    IDEB_AF DECIMAL(3, 1),
    IDEB_EM DECIMAL(3, 1),
    PIB_PER_CAPITA DECIMAL(15, 2),
    COBERTURA_AGUA DECIMAL(5, 2),
    
    PRIMARY KEY CLUSTERED (NM_MUNICIPIO, ANO)
);


-- Dimensões calendário -------------------------

CREATE TABLE DIM_ANO (
    ANO INT PRIMARY KEY,
);
GO

CREATE TABLE DIM_DIA (
    ANO INT NOT NULL,
    DIA INT NOT NULL,
    DIA_SEMANA VARCHAR(20),

    PRIMARY KEY CLUSTERED (ANO, DIA),
    FOREIGN KEY (ANO) REFERENCES DIM_ANO (ANO)  
);
GO
-------------------------------------------------

CREATE TABLE DIM_QTDE_CHUVA (
  ANO INT,
  DIA INT,
  HORA INT,
  PRECIPITACAO_TOTAL_HORA FLOAT,
  UMIDADE_RELATIVA_AR FLOAT,

  PRIMARY KEY CLUSTERED (HORA, DIA, ANO)
)
GO

CREATE TABLE FATO_VOTOS (
    SQ_CANDIDATO INT,
    ANO INT,
    NR_TURNO INT,
    NR_ZONA INT,
    NR_SECAO INT,
    QT_APTOS INT,
    QT_COMPARECIMENTO INT,
    QT_ABSTENCOES INT,
    QT_VOTOS_NOMINAIS INT,
    QT_VOTOS_BRANCOS INT,
    QT_VOTOS_NULOS INT,
    QT_VOTOS_LEGENDA INT,
    QT_VOTOS_ANULADOS_APU_SEP INT
    PRIMARY KEY CLUSTERED (SQ_CANDIDATO, NR_SECAO, NR_TURNO, ANO)
);



-- Chaves Estrangeiras (Foreign Keys)

