SELECT 
    f.ANO_ELEICAO,
    f.NR_TURNO,
    f.CD_MUNICIPIO,
    f.NM_MUNICIPIO,
    f.NR_ZONA,
    f.NR_SECAO,
    f.QT_APTOS,
    f.QT_COMPARECIMENTO,
    f.QT_ABSTENCOES,
    f.QT_VOTOS_NOMINAIS,
    f.QT_VOTOS_BRANCOS,
    f.QT_VOTOS_NULOS,
    f.QT_VOTOS_LEGENDA,
    f.QT_VOTOS_ANULADOS_APU_SEP,
    COALESCE(NULLIF(f.NR_LOCAL_VOTACAO, 0), d.NR_LOCAL_VOTACAO) AS NR_LOCAL_VOTACAO,
    COALESCE(NULLIF(f.NM_LOCAL_VOTACAO, ''), d.NM_LOCAL_VOTACAO) AS NM_LOCAL_VOTACAO
FROM FATO_VOTOS f
INNER JOIN DIM_LOCALVOTACAO d
    ON  f.CD_MUNICIPIO = d.CD_MUNICIPIO
    AND f.NR_ZONA      = d.NR_ZONA
    AND f.NR_SECAO     = d.NR_SECAO
WHERE f.NM_LOCAL_VOTACAO = '' 
   OR f.NM_LOCAL_VOTACAO IS NULL
   OR f.NR_LOCAL_VOTACAO IS NULL;