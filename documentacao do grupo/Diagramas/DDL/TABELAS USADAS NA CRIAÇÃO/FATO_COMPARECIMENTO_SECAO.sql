-- 2. Rode o INSERT completo (com MIN para evitar locais duplicados na dimensão)
INSERT INTO FATO_COMPARECIMENTO_SECAO (
    SK_ELEICAO,
    SK_MUNICIPIO,
    SK_LOCAL_VOTACAO,
    NR_ZONA,
    NR_SECAO,
    QT_COMPARECIMENTO
)
SELECT
    COALESCE(ELE.SK_ELEICAO, -1)            AS SK_ELEICAO,
    COALESCE(MUN.SK_MUNICIPIO, -1)          AS SK_MUNICIPIO,
    COALESCE(MIN(LOC.SK_LOCAL_VOTACAO), -1) AS SK_LOCAL_VOTACAO,
    STG.NR_ZONA,
    STG.NR_SECAO,
    STG.QT_COMPARECIMENTO
FROM stg_Comparecimento AS STG
LEFT JOIN DIM_ELEICAO AS ELE
    ON  ELE.ANO_ELEICAO = STG.ANO_ELEICAO
    AND ELE.NR_TURNO    = STG.NR_TURNO
LEFT JOIN DIM_MUNICIPIO AS MUN
    ON  MUN.CD_MUNICIPIO = STG.CD_MUNICIPIO
LEFT JOIN DIM_LOCAL_VOTACAO AS LOC
    ON  LOC.ANO_ELEICAO      = STG.ANO_ELEICAO
    AND LOC.CD_MUNICIPIO     = STG.CD_MUNICIPIO
    AND LOC.NR_ZONA          = STG.NR_ZONA
    AND LOC.NR_LOCAL_VOTACAO = STG.NR_LOCAL_VOTACAO
GROUP BY
    ELE.SK_ELEICAO,
    MUN.SK_MUNICIPIO,
    STG.CD_MUNICIPIO,
    STG.NR_ZONA,
    STG.NR_SECAO,
    STG.QT_COMPARECIMENTO;
GO

