-- ============================================================================
-- BLOCO 1: DIMENSÕES CONFORMADAS (Chaves Substitutas Inteiras)
-- ============================================================================

-- 1.1 Dimensão Calendário (substitui DIM_ANO e DIM_DIA com suporte nativo a DATE)
CREATE TABLE DIM_CALENDARIO (
    SK_DATA        INT         NOT NULL PRIMARY KEY, -- Formato YYYYMMDD (ex: 20141005)
    DATA           DATE        NOT NULL UNIQUE,
    ANO            INT         NOT NULL,
    MES            TINYINT     NOT NULL,
    NOME_MES       VARCHAR(20) NOT NULL,
    DIA            TINYINT     NOT NULL,
    DIA_SEMANA     VARCHAR(20) NOT NULL,
    TRIMESTRE      TINYINT     NOT NULL,
    EH_DIA_ELEICAO BIT         NOT NULL DEFAULT 0
);
GO

-- 1.2 Dimensão Eleição (centraliza ano, código da eleição e turno)
CREATE TABLE DIM_ELEICAO (
    SK_ELEICAO  INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ANO_ELEICAO INT               NOT NULL,
    CD_ELEICAO  INT               NOT NULL,
    NR_TURNO    TINYINT           NOT NULL,
    CONSTRAINT UQ_DIM_ELEICAO UNIQUE (ANO_ELEICAO, CD_ELEICAO, NR_TURNO)
);
GO

-- 1.3 Dimensão Município (dimensão conformada compartilhada pelas 4 fatos)
CREATE TABLE DIM_MUNICIPIO (
    SK_MUNICIPIO INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    CD_MUNICIPIO INT               NOT NULL UNIQUE,
    NM_MUNICIPIO VARCHAR(255)      NOT NULL
);
GO

-- 1.4 Dimensão Local de Votação (unifica DIM_LOCALVOTACAO e DIM_POSICAOGEOGRAFICA)
-- Granularidade: Local físico de votação por eleição (Seção fica como dimensão degenerada nas fatos)

CREATE TABLE DIM_LOCAL_VOTACAO (
    SK_LOCAL_VOTACAO           INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ANO_ELEICAO                INT               NOT NULL,
    CD_MUNICIPIO               INT               NOT NULL,
    NM_MUNICIPIO               VARCHAR(255)      NOT NULL, -- Desnormalizado propositalmente (Kimball)
    NR_ZONA                    INT               NOT NULL,
    NR_LOCAL_VOTACAO           INT               NOT NULL,
    NM_LOCAL_VOTACAO           VARCHAR(150)      NULL,
    DS_ENDERECO                VARCHAR(255)      NULL,
    NM_BAIRRO                  VARCHAR(100)      NULL,
    NR_CEP                     CHAR(8)           NULL,
    NR_LATITUDE                DECIMAL(18, 6)     NULL,
    NR_LONGITUDE               DECIMAL(18, 6)     NULL,
    CONSTRAINT UQ_DIM_LOCAL_VOTACAO UNIQUE (ANO_ELEICAO, CD_MUNICIPIO, NR_ZONA, NR_LOCAL_VOTACAO)
);
GO

-- 1.5 Dimensão Partido (inclui NR_PARTIDO para resolver votos de legenda no ETL)
CREATE TABLE DIM_PARTIDO (
    SK_PARTIDO     INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ANO_ELEICAO    INT               NOT NULL,
    NR_PARTIDO     INT               NOT NULL,
    SG_PARTIDO     VARCHAR(20)       NOT NULL,
    NM_PARTIDO     NVARCHAR(100)      NOT NULL,
    POSICIONAMENTO VARCHAR(20)       NOT NULL, -- 'SITUAÇÃO', 'OPOSIÇÃO', 'NÃO SE APLICA'
    CONSTRAINT UQ_DIM_PARTIDO UNIQUE (ANO_ELEICAO, SG_PARTIDO)
);
GO

-- 1.6 Dimensão Candidato

CREATE TABLE DIM_CANDIDATO (
    SK_CANDIDATO INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    SQ_CANDIDATO BIGINT            NOT NULL,
    ANO_ELEICAO  INT               NOT NULL,
    NR_CANDIDATO INT               NULL,
    NM_CANDIDATO NVARCHAR(100)     NOT NULL,
    NR_PARTIDO   INT               NULL,
    SG_PARTIDO   VARCHAR(20)       NULL,
    NM_PARTIDO   NVARCHAR(100)     NULL,
    CONSTRAINT UQ_DIM_CANDIDATO UNIQUE (SQ_CANDIDATO, ANO_ELEICAO)
);
GO

-- 1.7 Dimensão Faixa Etária (extraída de FATO_VOTOS para remover texto da fato)
CREATE TABLE DIM_FAIXA_ETARIA (
    SK_FAIXA_ETARIA INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    DS_FAIXA_ETARIA VARCHAR(50)       NOT NULL UNIQUE,
    ORDEM_FAIXA     TINYINT           NOT NULL, -- Garante ordenação cronológica no Power BI
    DS_CATEGORIA_ETARIA VARCHAR(50)       NULL
);
GO

-- 1.8 Dimensão Classificação IDHM Proxy (extraída de DIM_IDHM_PROXY)
CREATE TABLE DIM_CLASSIFICACAO_IDHM (
    SK_CLASSIFICACAO_IDHM INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    FAIXA_URBANO_RURAL    VARCHAR(30)       NOT NULL UNIQUE,
    ORDEM_FAIXA           TINYINT           NOT NULL
);
GO

