-- ============================================================================
-- BLOCO 3: CONSTELAÇÃO DE FATOS (Apenas SKs Inteiras + Métricas Numéricas)
-- ============================================================================

-- 3.1 Fato Resultados (Votação nominal, de legenda, brancos e nulos por seção)
CREATE TABLE FATO_RESULTADOS (
    SK_DATA          INT NOT NULL,
    SK_ELEICAO       INT NOT NULL,
    SK_MUNICIPIO     INT NOT NULL,
    SK_LOCAL_VOTACAO INT NOT NULL,
    SK_CANDIDATO     INT NOT NULL, -- Usa -1 para votos de legenda, brancos e nulos
    SK_PARTIDO       INT NOT NULL, -- Usa -1 para brancos, nulos e anulados
    NR_SECAO         INT NOT NULL, -- Dimensão Degenerada (DD)
    NR_VOTAVEL       INT NOT NULL, -- Dimensão Degenerada (DD: nº candidato, nº partido ou 95/96/97)
    QT_VOTOS         INT NOT NULL,
    NR_ZONA          INT NOT NULL,
    NR_LOCAL_VOTACAO INT NOT NULL

    CONSTRAINT PK_FATO_RESULTADOS PRIMARY KEY CLUSTERED (
        SK_DATA, SK_ELEICAO, SK_MUNICIPIO, SK_LOCAL_VOTACAO, NR_SECAO, SK_CANDIDATO, SK_PARTIDO, NR_VOTAVEL, NR_ZONA, NR_LOCAL_VOTACAO
    ),
    CONSTRAINT FK_FR_CALENDARIO FOREIGN KEY (SK_DATA)          REFERENCES DIM_CALENDARIO (SK_DATA),
    CONSTRAINT FK_FR_ELEICAO    FOREIGN KEY (SK_ELEICAO)       REFERENCES DIM_ELEICAO (SK_ELEICAO),
    CONSTRAINT FK_FR_MUNICIPIO  FOREIGN KEY (SK_MUNICIPIO)     REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FR_LOCAL      FOREIGN KEY (SK_LOCAL_VOTACAO) REFERENCES DIM_LOCAL_VOTACAO (SK_LOCAL_VOTACAO),
    CONSTRAINT FK_FR_CANDIDATO  FOREIGN KEY (SK_CANDIDATO)     REFERENCES DIM_CANDIDATO (SK_CANDIDATO),
    CONSTRAINT FK_FR_PARTIDO    FOREIGN KEY (SK_PARTIDO)       REFERENCES DIM_PARTIDO (SK_PARTIDO)
);

-- 3.2 Fato Votos (Comparecimento, abstenção e perfil do eleitorado por seção/faixa etária)
CREATE TABLE FATO_COMPARECIMENTO_SECAO (
    SK_ELEICAO         INT NOT NULL,
    SK_MUNICIPIO       INT NOT NULL,
    SK_LOCAL_VOTACAO   INT NOT NULL,
    NR_ZONA            INT NOT NULL, -- Dimensão Degenerada (DD)
    NR_SECAO           INT NOT NULL, -- Dimensão Degenerada (DD)
    QT_COMPARECIMENTO  INT NOT NULL,

    CONSTRAINT PK_FATO_COMPARECIMENTO PRIMARY KEY CLUSTERED (
        SK_ELEICAO, SK_MUNICIPIO, NR_ZONA, NR_SECAO
    ),
    CONSTRAINT FK_FCS_ELEICAO   FOREIGN KEY (SK_ELEICAO)       REFERENCES DIM_ELEICAO (SK_ELEICAO),
    CONSTRAINT FK_FCS_MUNICIPIO FOREIGN KEY (SK_MUNICIPIO)     REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FCS_LOCAL     FOREIGN KEY (SK_LOCAL_VOTACAO) REFERENCES DIM_LOCAL_VOTACAO (SK_LOCAL_VOTACAO)
);
GO

-- Eleitorado apto por seção × faixa etária (única fonte de QT_APTOS)
CREATE TABLE FATO_ELEITORADO (
    SK_ELEICAO        INT NOT NULL,
    SK_MUNICIPIO      INT NOT NULL,
    SK_LOCAL_VOTACAO  INT NOT NULL,
    NR_ZONA           INT NOT NULL, -- Dimensão Degenerada (DD)
    NR_SECAO          INT NOT NULL, -- Dimensão Degenerada (DD)
    SK_FAIXA_ETARIA   INT NOT NULL,
    QT_APTOS          INT NOT NULL,

    CONSTRAINT PK_FATO_ELEITORADO PRIMARY KEY CLUSTERED (
        SK_ELEICAO, SK_MUNICIPIO, NR_ZONA, NR_SECAO, SK_FAIXA_ETARIA
    ),
    CONSTRAINT FK_FE_ELEICAO      FOREIGN KEY (SK_ELEICAO)       REFERENCES DIM_ELEICAO (SK_ELEICAO),
    CONSTRAINT FK_FE_MUNICIPIO    FOREIGN KEY (SK_MUNICIPIO)     REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FE_LOCAL        FOREIGN KEY (SK_LOCAL_VOTACAO) REFERENCES DIM_LOCAL_VOTACAO (SK_LOCAL_VOTACAO),
    CONSTRAINT FK_FE_FAIXA_ETARIA FOREIGN KEY (SK_FAIXA_ETARIA)  REFERENCES DIM_FAIXA_ETARIA (SK_FAIXA_ETARIA)
);
GO
-- 3.3 Fato Indicadores Município (substitui DIM_IDHM_PROXY como fato periódica)
-- Dica ETL: vincular SK_DATA ao 1º dia do ano de referência (ex: 20140101, 20180101, 20220101)
CREATE TABLE FATO_INDICADORES_MUNICIPIO (
    SK_DATA               INT            NOT NULL,
    SK_MUNICIPIO          INT            NOT NULL,
    SK_CLASSIFICACAO_IDHM INT            NOT NULL,
    IDEB_AI               DECIMAL(3, 1)  NULL,
    IDEB_AF               DECIMAL(3, 1)  NULL,
    IDEB_EM               DECIMAL(3, 1)  NULL,
    PIB_PER_CAPITA        DECIMAL(15, 2) NULL,
    COBERTURA_AGUA        DECIMAL(5, 2)  NULL,
    ESCALA_URBANO_RURAL   DECIMAL(5, 4)  NULL,

    CONSTRAINT PK_FATO_INDICADORES_MUNICIPIO PRIMARY KEY CLUSTERED (SK_DATA, SK_MUNICIPIO),
    CONSTRAINT FK_FIM_CALENDARIO    FOREIGN KEY (SK_DATA)               REFERENCES DIM_CALENDARIO (SK_DATA),
    CONSTRAINT FK_FIM_MUNICIPIO     FOREIGN KEY (SK_MUNICIPIO)          REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FIM_CLASSIFICACAO FOREIGN KEY (SK_CLASSIFICACAO_IDHM) REFERENCES DIM_CLASSIFICACAO_IDHM (SK_CLASSIFICACAO_IDHM)
);
GO

-- 3.4 Fato Clima Local (substitui DIM_QT_CHUVA como fato meteorológica por local/data)
CREATE TABLE FATO_CLIMA_LOCAL (
    SK_DATA             INT           NOT NULL,
    SK_MUNICIPIO        INT           NOT NULL,
    SK_LOCAL_VOTACAO    INT           NOT NULL,
    PRECIPITACAO_TOTAL  DECIMAL(8, 2) NULL,
    UMIDADE_RELATIVA_AR DECIMAL(5, 2) NULL,

    CONSTRAINT PK_FATO_CLIMA_LOCAL PRIMARY KEY CLUSTERED (SK_DATA, SK_LOCAL_VOTACAO),
    CONSTRAINT FK_FCL_CALENDARIO FOREIGN KEY (SK_DATA)          REFERENCES DIM_CALENDARIO (SK_DATA),
    CONSTRAINT FK_FCL_MUNICIPIO  FOREIGN KEY (SK_MUNICIPIO)     REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FCL_LOCAL      FOREIGN KEY (SK_LOCAL_VOTACAO) REFERENCES DIM_LOCAL_VOTACAO (SK_LOCAL_VOTACAO)
);
GO