INSERT INTO FATO_ELEITORADO (
    SK_ELEICAO,
    SK_MUNICIPIO,
    SK_LOCAL_VOTACAO,
    NR_ZONA,
    NR_SECAO,
    SK_FAIXA_ETARIA,
    QT_APTOS
)
SELECT
    COALESCE(ELEI.SK_ELEICAO, -1)           AS SK_ELEICAO,
    COALESCE(MUN.SK_MUNICIPIO, -1)          AS SK_MUNICIPIO,
    COALESCE(MIN(LOC.SK_LOCAL_VOTACAO), -1) AS SK_LOCAL_VOTACAO,
    STG.NR_ZONA,
    STG.NR_SECAO,
    COALESCE(FE.SK_FAIXA_ETARIA, -1)        AS SK_FAIXA_ETARIA,
    SUM(STG.QT_APTOS)                       AS QT_APTOS
FROM stg_Aptos AS STG
LEFT JOIN DIM_ELEICAO AS ELEI
    ON  ELEI.ANO_ELEICAO = STG.ANO_ELEICAO
    AND ELEI.NR_TURNO    = STG.NR_TURNO
LEFT JOIN DIM_MUNICIPIO AS MUN
    ON  MUN.CD_MUNICIPIO = STG.CD_MUNICIPIO
LEFT JOIN DIM_LOCAL_VOTACAO AS LOC
    ON  LOC.ANO_ELEICAO      = STG.ANO_ELEICAO
    AND LOC.CD_MUNICIPIO     = STG.CD_MUNICIPIO
    AND LOC.NR_ZONA          = STG.NR_ZONA
    AND LOC.NR_LOCAL_VOTACAO = STG.NR_LOCAL_VOTACAO
LEFT JOIN DIM_FAIXA_ETARIA AS FE
    ON  FE.DS_CATEGORIA_ETARIA = STG.DS_FAIXA_ETARIA
GROUP BY
    COALESCE(ELEI.SK_ELEICAO, -1),
    COALESCE(MUN.SK_MUNICIPIO, -1),
    STG.CD_MUNICIPIO,
    STG.NR_ZONA,
    STG.NR_SECAO,
    COALESCE(FE.SK_FAIXA_ETARIA, -1);
GO